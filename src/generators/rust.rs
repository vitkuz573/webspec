fn generate_extraction(
    field_name: &str,
    field_def: &crate::spec::FieldDef,
    is_optional: bool,
    spec: &ApiSpec,
) -> String {
    let raw_type = &field_def.r#type;
    let inner_type = if raw_type.starts_with("Option<") && raw_type.ends_with('>') {
        &raw_type[7..raw_type.len() - 1]
    } else {
        raw_type.as_str()
    };

    if is_vec_type(inner_type) {
        return format!("let {} = Vec::new();", field_name);
    }
    if is_entity_type(inner_type, spec) {
        if let Some(entity) = spec.entities.get(inner_type) {
            if let Some(fields) = &entity.fields {
                let field_inits: Vec<String> = fields
                    .iter()
                    .map(|(fname, fdef)| {
                        let ftype = &fdef.r#type;
                        if is_newtype(spec, ftype) {
                            format!("{}: {}::new(0)", fname, ftype)
                        } else if ftype == "u32" {
                            format!("{}: 0u32", fname)
                        } else if ftype == "f64" || is_numeric_type(ftype, spec) {
                            format!("{}: 0.0", fname)
                        } else if is_bool_type(ftype) {
                            format!("{}: false", fname)
                        } else if is_enum_type(ftype, spec) {
                            format!("{}: Default::default()", fname)
                        } else if ftype == "String" {
                            format!("{}: String::new()", fname)
                        } else if is_vec_type(ftype) {
                            format!("{}: Vec::new()", fname)
                        } else if ftype.starts_with("Option<") {
                            format!("{}: None", fname)
                        } else {
                            format!("{}: Default::default()", fname)
                        }
                    })
                    .collect();
                return format!(
                    "let {} = {} {{ {} }};",
                    field_name,
                    inner_type,
                    field_inits.join(", ")
                );
            }
        }
        return format!("let {} = {} {{}};", field_name, inner_type);
    }

    let needs_enum_conv = is_enum_type(inner_type, spec);
    let needs_id_conv = is_newtype(spec, inner_type);
    let needs_num_conv = is_numeric_type(inner_type, spec);
    let needs_bool_conv = is_bool_type(inner_type);
    let needs_conversion =
        needs_enum_conv || needs_id_conv || needs_num_conv || needs_bool_conv;

    if let Some(attr) = &field_def.attribute {
        if let Some(sel) = &field_def.selector {
            if needs_conversion || is_optional {
                format!(
                    "let {} = extract_attr(&el, \"{}\", \"{}\");",
                    field_name, sel, attr
                )
            } else {
                format!(
                    "let {} = extract_attr(&el, \"{}\", \"{}\").unwrap_or_default();",
                    field_name, sel, attr
                )
            }
        } else if needs_conversion || is_optional {
            format!(
                "let {} = el.value().attr(\"{}\").map(|s| s.to_string());",
                field_name, attr
            )
        } else {
            format!(
                "let {} = el.value().attr(\"{}\").map(|s| s.to_string()).unwrap_or_default();",
                field_name, attr
            )
        }
    } else if let Some(sel) = &field_def.selector {
        if needs_conversion || is_optional {
            format!("let {} = extract_text(&el, \"{}\");", field_name, sel)
        } else {
            format!(
                "let {} = extract_text(&el, \"{}\").unwrap_or_default();",
                field_name, sel
            )
        }
    } else if is_optional {
        format!("let {}: Option<String> = None;", field_name)
    } else {
        format!("let {} = String::new();", field_name)
    }
}

fn generate_conversion(_field_name: &str, field_type: &str, spec: &ApiSpec) -> String {
    if field_type.starts_with("Option<") && field_type.ends_with('>') {
        let inner = &field_type[7..field_type.len() - 1];
        if is_enum_type(inner, spec) {
            if let Some(enum_def) = spec.enums.get(inner) {
                let arms: Vec<String> = enum_def
                    .values
                    .keys()
                    .map(|v| enum_match_arm(v, inner))
                    .collect();
                return format!(
                    ".and_then(|s| match s.as_str() {{ {}, _ => None }})",
                    arms.join(", ")
                );
            }
        }
        if is_newtype(spec, inner) {
            return format!(".and_then(|s| s.parse::<{}>().ok())", inner);
        }
        if is_numeric_type(inner, spec) {
            return format!(".and_then(|s| s.parse::<{}>().ok())", inner);
        }
        if is_entity_type(inner, spec) {
            return "None".to_string();
        }
        return String::new();
    }

    if is_vec_type(field_type) {
        return String::new();
    }

    if is_enum_type(field_type, spec) {
        if let Some(enum_def) = spec.enums.get(field_type) {
            let arms: Vec<String> = enum_def
                .values
                .keys()
                .map(|v| enum_match_arm(v, field_type))
                .collect();
            return format!(
                ".and_then(|s| match s.as_str() {{ {}, _ => None }}).unwrap_or_default()",
                arms.join(", ")
            );
        }
    }
    if is_newtype(spec, field_type) {
        return format!(
            ".and_then(|s| s.parse::<{}>().ok()).unwrap_or_default()",
            field_type
        );
    }
    if is_numeric_type(field_type, spec) {
        return format!(
            ".and_then(|s| s.parse::<{}>().ok()).unwrap_or_default()",
            field_type
        );
    }
    if is_bool_type(field_type) {
        return ".and_then(|s| s.parse::<bool>().ok()).unwrap_or_default()".to_string();
    }
    if is_entity_type(field_type, spec) {
        return String::new();
    }
    String::new()
}

// ── client.rs ───────────────────────────────────────────────────────

fn generate_client(spec: &ApiSpec) -> String {
    let err = error_name(spec);
    let client = client_name(spec);
    let base_url = spec.base_url.as_deref().unwrap_or("https://example.com");

    let mut o = String::from("// @generated by specgen — DO NOT EDIT\n\n");
    o.push_str(&format!(
        "use reqwest::Client;\nuse crate::error::{};\nuse crate::models::*;\nuse crate::parser::Parser;\n\n",
        err
    ));
    o.push_str(&format!("pub const DEFAULT_BASE_URL: &str = \"{}\";\n\n", base_url));
    o.push_str(&format!("pub struct {} {{\n", client));
    o.push_str("    pub client: Client,\n");
    o.push_str("    pub base_url: String,\n");
    o.push_str("}\n\n");

    o.push_str(&format!("impl {} {{\n", client));
    o.push_str(&format!("    pub fn new() -> Result<Self, {}> {{\n", err));
    o.push_str("        Self::with_base_url(DEFAULT_BASE_URL)\n");
    o.push_str("    }\n\n");

    o.push_str(&format!(
        "    pub fn with_base_url(base_url: &str) -> Result<Self, {}> {{\n",
        err
    ));
    o.push_str("        let client = Client::builder()\n");
    o.push_str("            .user_agent(\"Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36\")\n");
    o.push_str("            .cookie_store(true)\n");
    o.push_str("            .timeout(std::time::Duration::from_secs(30))\n");
    o.push_str("            .build()?;\n");
    o.push_str("        Ok(Self { client, base_url: base_url.to_string() })\n");
    o.push_str("    }\n\n");

    o.push_str(&format!(
        "    pub async fn get(&self, path: &str) -> Result<String, {}> {{\n",
        err
    ));
    o.push_str("        let url = if path.starts_with(\"http\") {\n");
    o.push_str("            path.to_string()\n");
    o.push_str("        } else {\n");
    o.push_str("            format!(\"{}{}\", self.base_url, path)\n");
    o.push_str("        };\n");
    o.push_str("        let resp = self.client.get(&url).send().await?;\n");
    o.push_str("        Ok(resp.text().await?)\n");
    o.push_str("    }\n\n");

    for (page_name, page_def) in &spec.pages {
        let entity_name = &page_def.entity;
        let url_pattern = page_def.url_pattern.as_ref().or(page_def.url.as_ref());

        if let Some(url_pattern) = url_pattern {
            let params: Vec<String> = {
                let mut params = Vec::new();
                let mut chars = url_pattern.chars().peekable();
                while let Some(c) = chars.next() {
                    if c == '{' {
                        let mut param = String::new();
                        while let Some(&nc) = chars.peek() {
                            if nc == '}' {
                                chars.next();
                                break;
                            }
                            param.push(nc);
                            chars.next();
                        }
                        params.push(param);
                    }
                }
                params
            };

            let params_str = if params.is_empty() {
                String::new()
            } else {
                params
                    .iter()
                    .map(|p| format!("{}: u64", p))
                    .collect::<Vec<_>>()
                    .join(", ")
            };

            let mut url_format = url_pattern.clone();
            for p in &params {
                url_format = url_format.replace(&format!("{{{}}}", p), "{}");
            }

            let is_list = page_def.list_selector.is_some();
            let return_type = if is_list {
                format!("Vec<{}>", entity_name)
            } else {
                entity_name.to_string()
            };

            let method_name = format!("fetch_{}", page_name);
            o.push_str(&format!(
                "    pub async fn {}(&self, {}) -> Result<{}, {}> {{\n",
                method_name, params_str, return_type, err
            ));

            if params.is_empty() {
                o.push_str(&format!(
                    "        let html = self.get(\"{}\").await?;\n",
                    url_pattern
                ));
            } else {
                o.push_str(&format!(
                    "        let html = self.get(&format!(\"{}\", {})).await?;\n",
                    url_format,
                    params.join(", ")
                ));
            }

            if is_list {
                o.push_str(&format!(
                    "        Ok(Parser::new().parse_{}(&html))\n",
                    page_name
                ));
            } else {
                o.push_str(&format!(
                    "        Parser::new().parse_{}(&html).ok_or_else(|| {}::Parse(crate::error::ParseError::MissingField(\"{}\".into())))\n",
                    page_name, err, entity_name
                ));
            }
            o.push_str("    }\n\n");
        }
    }

    o.push_str("}\n");
    o
}

