use crate::spec::ApiSpec;
use crate::traits::{GeneratedOutput, LanguageGenerator};

pub struct RustGenerator;

impl LanguageGenerator for RustGenerator {
    fn target(&self) -> &str {
        "rust"
    }

    fn file_extension(&self) -> &str {
        "rs"
    }

    fn generate(&self, spec: &ApiSpec) -> GeneratedOutput {
        let mut files = Vec::new();

        files.push(("Cargo.toml".into(), generate_cargo_toml(spec)));
        files.push(("src/lib.rs".into(), generate_lib_rs(spec)));
        files.push(("src/models.rs".into(), generate_models(spec)));
        files.push(("src/parser.rs".into(), generate_parser(spec)));
        files.push(("src/client.rs".into(), generate_client(spec)));
        files.push(("src/error.rs".into(), generate_error(spec)));

        GeneratedOutput { files }
    }
}

fn pascal_case(s: &str) -> String {
    s.split('_')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
            }
        })
        .collect()
}

fn crate_name(spec: &ApiSpec) -> String {
    spec.name.to_lowercase().replace(' ', "-").replace('_', "-")
}

fn client_name(spec: &ApiSpec) -> String {
    format!("{}Client", pascal_case(&spec.name))
}

fn error_name(spec: &ApiSpec) -> String {
    format!("{}Error", pascal_case(&spec.name))
}

fn newtype_names(spec: &ApiSpec) -> Vec<String> {
    spec.types
        .iter()
        .filter(|(_, m)| m.newtype.unwrap_or(false))
        .map(|(name, _)| name.clone())
        .collect()
}

fn is_newtype(spec: &ApiSpec, type_name: &str) -> bool {
    spec.types
        .get(type_name)
        .map(|m| m.newtype.unwrap_or(false))
        .unwrap_or(false)
}

fn is_enum_type(type_name: &str, spec: &ApiSpec) -> bool {
    spec.enums.contains_key(type_name)
}

fn is_entity_type(type_name: &str, spec: &ApiSpec) -> bool {
    spec.entities.contains_key(type_name)
}

fn resolve_type(type_name: &str, nullable: bool, spec: &ApiSpec) -> String {
    // Handle Option<X> — resolve the inner type and wrap back
    if type_name.starts_with("Option<") && type_name.ends_with('>') {
        let inner = &type_name[7..type_name.len() - 1];
        let resolved_inner = resolve_type_raw(inner, spec);
        return format!("Option<{}>", resolved_inner);
    }

    let resolved = resolve_type_raw(type_name, spec);

    if nullable && !resolved.starts_with("Option") {
        format!("Option<{}>", resolved)
    } else {
        resolved
    }
}

fn resolve_type_raw(type_name: &str, spec: &ApiSpec) -> String {
    if spec.enums.contains_key(type_name) || spec.entities.contains_key(type_name) {
        return type_name.to_string();
    }

    if let Some(tm) = spec.types.get(type_name) {
        if tm.newtype.unwrap_or(false) {
            return type_name.to_string();
        }
        if let Some(rust) = &tm.rust {
            return rust.clone();
        }
    }

    match type_name {
        "string" => "String".to_string(),
        "decimal" | "f64" => "f64".to_string(),
        "u32" => "u32".to_string(),
        "bool" => "bool".to_string(),
        "date" | "datetime" => "Option<String>".to_string(),
        "url" => "String".to_string(),
        other => other.to_string(),
    }
}

fn is_numeric_type(type_name: &str, spec: &ApiSpec) -> bool {
    if let Some(tm) = spec.types.get(type_name) {
        if let Some(rust) = &tm.rust {
            return matches!(rust.as_str(), "f64" | "u32" | "i64" | "u64");
        }
    }
    matches!(type_name, "f64" | "u32" | "i64" | "u64" | "Price")
}

fn is_bool_type(type_name: &str) -> bool {
    type_name == "bool"
}

fn is_vec_type(type_name: &str) -> bool {
    type_name.starts_with("Vec<")
}

fn enum_match_arm(variant: &str, enum_name: &str) -> String {
    let camel = pascal_case(variant);
    format!("\"{}\" => Some({}::{})", variant, enum_name, camel)
}

