fn generate_models(spec: &ApiSpec) -> String {
    let mut o = String::from("// @generated by specgen — DO NOT EDIT\n\n");
    o.push_str("use serde::{Deserialize, Serialize};\nuse std::hash::Hash;\n\n");

    let newtypes = newtype_names(spec);
    if !newtypes.is_empty() {
        o.push_str(&generate_newtypes_block(spec));
        o.push('\n');
    }

    for (name, enum_def) in &spec.enums {
        o.push_str(&format!(
            "#[derive(Debug, Clone, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]\npub enum {} {{\n",
            name
        ));
        let mut first = true;
        for (variant, _) in &enum_def.values {
            let camel = pascal_case(variant);
            if first {
                o.push_str(&format!(
                    "    #[default]\n    #[serde(rename = \"{}\")]\n    {},\n",
                    variant, camel
                ));
                first = false;
            } else {
                o.push_str(&format!(
                    "    #[serde(rename = \"{}\")]\n    {},\n",
                    variant, camel
                ));
            }
        }
        o.push_str("}\n\n");

        o.push_str(&format!("impl std::fmt::Display for {} {{\n", name));
        o.push_str("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {\n");
        o.push_str("        match self {\n");
        for (variant, _) in &enum_def.values {
            let camel = pascal_case(variant);
            o.push_str(&format!(
                "            {}::{} => write!(f, \"{}\"),\n",
                name, camel, variant
            ));
        }
        o.push_str("        }\n");
        o.push_str("    }\n}\n\n");
    }

    for (name, entity) in &spec.entities {
        if let Some(fields) = &entity.fields {
            o.push_str(&format!(
                "#[derive(Debug, Clone, Serialize, Deserialize)]\npub struct {} {{\n",
                name
            ));
            for (field_name, field_def) in fields {
                let rust_type = resolve_type(&field_def.r#type, field_def.nullable.unwrap_or(false), spec);
                o.push_str(&format!("    pub {}: {},\n", field_name, rust_type));
            }
            o.push_str("}\n\n");
        }
    }

    o
}

fn generate_newtypes_block(spec: &ApiSpec) -> String {
    let mut o = String::new();
    o.push_str(
        r#"pub trait IdType: std::fmt::Display + std::str::FromStr + Clone + Copy + PartialEq + Eq + Hash {
    fn new(id: u64) -> Self;
    fn inner(self) -> u64;
}

macro_rules! define_id_type {
    ($name:ident) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]
        pub struct $name(u64);

        impl $name {
            pub fn new(id: u64) -> Self { Self(id) }
            pub fn inner(self) -> u64 { self.0 }
        }

        impl std::fmt::Display for $name {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                write!(f, "{}", self.0)
            }
        }

        impl std::str::FromStr for $name {
            type Err = std::num::ParseIntError;
            fn from_str(s: &str) -> Result<Self, Self::Err> { Ok(Self(s.parse()?)) }
        }
    };
}

"#,
    );

    for (name, tm) in &spec.types {
        if !tm.newtype.unwrap_or(false) {
            continue;
        }
        let rust_type = tm.rust.as_deref().unwrap_or("u64");
        if rust_type == "u64" || rust_type == "u32" {
            o.push_str(&format!("define_id_type!({});\n", name));
        } else {
            let (extra_derives, extra_impls) = if rust_type == "f64" {
                (
                    "",
                    r#"
impl Default for NAME {
    fn default() -> Self { Self(0.0) }
}

impl std::str::FromStr for NAME {
    type Err = std::num::ParseFloatError;
    fn from_str(s: &str) -> Result<Self, Self::Err> { Ok(Self(s.parse()?)) }
}
"#,
                )
            } else {
                (
                    ", Eq, Hash",
                    r#"
impl std::str::FromStr for NAME {
    type Err = std::string::ParseError;
    fn from_str(s: &str) -> Result<Self, Self::Err> { Ok(Self(s.to_string())) }
}
"#,
                )
            };
            let impls = extra_impls.replace("NAME", name);
            o.push_str(&format!(
                "#[derive(Debug, Clone, PartialEq{}, Serialize, Deserialize)]\npub struct {}(pub {});\n\nimpl {} {{\n    pub fn new(v: impl Into<{}>) -> Self {{ Self(v.into()) }}\n    pub fn inner(&self) -> &{} {{ &self.0 }}\n}}\n\nimpl std::fmt::Display for {} {{\n    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{\n        write!(f, \"{{}}\", self.0)\n    }}\n}}\n{}\n",
                extra_derives, name, rust_type, name, rust_type, rust_type, name, impls
            ));
        }
    }

    o
}

